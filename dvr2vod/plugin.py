"""DVR2VOD - publish completed DVR recordings as a VOD-style playlist.

Dispatcharr records to disk, but recordings are only reachable through the
web UI: clients like TiviMate never see them (Dispatcharr issue #799). The
building blocks all exist on Dispatcharr's side - a recordings list API, a
per-recording file endpoint with Range/seek support that accepts a
``?token=`` query parameter, and channel logos for poster fallback. This
plugin wires them together without touching Dispatcharr's core:

    completed recordings -> dvr2vod/data/recordings.m3u
    each entry           -> {base_url}/api/channels/recordings/{id}/file/?token=...

Point any player that accepts an M3U URL (or Dispatcharr's own M3U import,
or a plain file mount) at the generated playlist and recordings show up
grouped per show, newest first.

Threading contract (same as clapparr): the ``recording_end`` event is
dispatched synchronously inside the recording task on a Celery worker, so
the handler must not block. It hands off to a daemon thread, and that
thread calls ``close_old_connections()`` in its ``finally`` block because
it touches the ORM.

The auth token never reaches the logs: it is interpolated into URLs only,
and every log line about the playlist prints the token-free path/counts.
"""

import os
import threading

from . import catalog

PLUGIN_KEY = catalog.PLUGIN_KEY

# Markers this plugin writes into the playlist header comment block, used by
# the status action to report the last generation time without a state file.
_GENERATED_TAG = "# Generated by DVR2VOD at"


class Plugin:
    fields = []
    actions = []

    def __init__(self):
        # Own data dir, sibling of the plugin package (same pattern as
        # vod-manager): Dispatcharr's plugin update path replaces only the
        # plugin's own folder, so a sibling folder survives updates.
        data_dir = os.environ.get(
            "DVR2VOD_DATA_DIR",
            os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), f"{PLUGIN_KEY}_data"),
        )
        self.data_dir = data_dir

    # ------------------------------------------------------------------ orm

    def _recording_rows(self):
        """Completed recordings as plain dicts for the pure catalog code.

        Field notes from Dispatcharr's actual model (apps/channels/models.py):
        Recording has NO status or name column - status, the program title
        and file_path all live inside custom_properties, and duration is
        end_time - start_time. A recording only enters the playlist once its
        file exists (custom_properties.file_path), because the playback
        endpoint serves that file; entries without one would 404.
        """
        from apps.channels.models import Recording

        rows = []
        qs = Recording.objects.select_related("channel", "channel__logo").order_by("-id")
        for rec in qs:
            cp = rec.custom_properties or {}
            # "stopped" = interrupted; still a finished file, so keep it.
            if cp.get("status") not in ("completed", "stopped"):
                continue
            if not cp.get("file_path"):
                continue
            channel_name = getattr(rec.channel, "name", "") or ""
            title = cp.get("program_title") or cp.get("program") or cp.get("title") or channel_name
            started_iso = ""
            if getattr(rec, "start_time", None):
                started_iso = rec.start_time.isoformat()
            duration_s = None
            if getattr(rec, "start_time", None) and getattr(rec, "end_time", None):
                try:
                    duration_s = int((rec.end_time - rec.start_time).total_seconds())
                except (TypeError, ValueError):
                    duration_s = None
            logo = getattr(getattr(rec.channel, "logo", None), "url", "") or ""
            rows.append(
                {
                    "id": rec.pk,
                    "title": title or "",
                    "started_iso": started_iso,
                    "duration_s": duration_s,
                    "logo": logo,
                }
            )
        return rows

    def _settings(self, context):
        s = dict(context.get("settings") or {})
        mode = s.get("library_mode") or catalog.MODE_SERIES
        return {
            "mode": mode if mode in (catalog.MODE_SERIES, catalog.MODE_FLAT) else catalog.MODE_SERIES,
            "group_title": (s.get("group_title") or "DVR Recordings").strip(),
            "base_url": (s.get("base_url") or "").strip().rstrip("/"),
            "token": (s.get("auth_token") or "").strip(),
            "output_path": (s.get("output_path") or "").strip(),
            "auto_regenerate": s.get("auto_regenerate", True) in (True, "true", "True", "on", 1, "1"),
        }

    def _output_file(self, cfg):
        if cfg["output_path"]:
            return cfg["output_path"]
        return os.path.join(self.data_dir, "recordings.m3u")

    def _base_url(self, cfg):
        if cfg["base_url"]:
            return cfg["base_url"]
        # Best effort without trusting request metadata: derive from the
        # first allowed host. Preview will flag it if it is unusable.
        try:
            from django.conf import settings as dj

            hosts = [h for h in (dj.ALLOWED_HOSTS or []) if h and h != "*"]
            if hosts:
                return f"http://{hosts[0]}:9191"
        except Exception:
            pass
        return ""

    # ------------------------------------------------------------- actions

    def run(self, action, params, context):
        log = context.get("logger")
        cfg = self._settings(context)

        if action == "on_recording_end":
            payload = (params or {}).get("payload") or {}
            rid = payload.get("recording_id") or payload.get("recordingId")
            if not cfg["auto_regenerate"]:
                return {"status": "skipped", "message": "Automatic regeneration is disabled"}
            if not rid:
                return {"status": "skipped", "message": "Event carried no recording_id"}
            threading.Thread(
                target=self._regenerate_quietly,
                args=(cfg, rid, log),
                name=f"{PLUGIN_KEY}-{rid}",
                daemon=True,
            ).start()
            return {"status": "ok", "message": f"Queued playlist rebuild for recording {rid}"}

        if action == "preview":
            return self._preview(cfg)

        if action == "generate_m3u":
            return self._generate(cfg, log)

        if action == "status":
            return self._status(cfg)

        return {"status": "error", "message": f"Unknown action '{action}'"}

    # -------------------------------------------------------------- helpers

    def _preview(self, cfg):
        rows = self._recording_rows()
        entries = catalog.build_entries(rows)
        base = self._base_url(cfg)
        playlist = catalog.render_m3u(
            entries, base, cfg["token"], mode=cfg["mode"], group_title=cfg["group_title"]
        )
        shows = sorted({e["show"] for e in entries})
        problems = []
        if not base:
            problems.append("No base URL configured and none could be derived - entries would have relative URLs.")
        if not cfg["token"]:
            problems.append("No access token configured - clients will get 403 from the recording file endpoint.")
        return {
            "status": "ok",
            "recordings": len(rows),
            "shows": shows[:25],
            "problems": problems,
            "playlist_head": "\n".join(playlist.splitlines()[:13]),
        }

    def _generate(self, cfg, log=None):
        rows = self._recording_rows()
        entries = catalog.build_entries(rows)
        playlist = catalog.render_m3u(
            entries, self._base_url(cfg), cfg["token"], mode=cfg["mode"], group_title=cfg["group_title"]
        )
        out = self._output_file(cfg)
        os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
        tmp = out + ".tmp"
        with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(f"{_GENERATED_TAG} entries={len(entries)}\n")
            fh.write(playlist)
        os.replace(tmp, out)
        if log:
            # Counts only - never the token, never entry URLs.
            log.info("[%s] wrote %s entries to %s", PLUGIN_KEY, len(entries), out)
        return {
            "status": "ok",
            "message": f"Wrote {len(entries)} entries to {out}",
            "entries": len(entries),
            "output_path": out,
        }

    def _status(self, cfg):
        from apps.channels.models import Recording

        # Same gate as _recording_rows: finished file in custom_properties.
        total = 0
        for cp in Recording.objects.values_list("custom_properties", flat=True):
            cp = cp or {}
            if cp.get("status") in ("completed", "stopped") and cp.get("file_path"):
                total += 1
        out = self._output_file(cfg)
        last = None
        entry_count = None
        if os.path.exists(out):
            try:
                with open(out, "r", encoding="utf-8") as fh:
                    head = fh.readline()
                    if head.startswith(_GENERATED_TAG):
                        rest = head[len(_GENERATED_TAG):].split()
                        if rest:
                            last = rest[0]
                    entry_count = sum(1 for line in fh if line.startswith("#EXTINF"))
            except OSError:
                pass
        return {
            "status": "ok",
            "completed_recordings": total,
            "output_path": out,
            "playlist_exists": os.path.exists(out),
            "last_generated": last,
            "playlist_entries": entry_count,
            "auto_regenerate": cfg["auto_regenerate"],
        }

    def _regenerate_quietly(self, cfg, rid, log):
        """Background rebuild after a recording ends. Never raises."""
        try:
            result = self._generate(cfg, log)
            if log:
                log.info("[%s] recording %s -> %s", PLUGIN_KEY, rid, result.get("message"))
        except Exception as exc:  # noqa: BLE001 - background thread must not die loudly
            if log:
                log.warning("[%s] playlist rebuild after recording %s failed: %s", PLUGIN_KEY, rid, exc)
        finally:
            try:
                from django.db import close_old_connections

                close_old_connections()
            except Exception:
                pass
